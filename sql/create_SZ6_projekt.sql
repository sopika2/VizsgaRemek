CREATE DATABASE IF NOT EXISTS studio13_gondozohaz;
USE studio13_gondozohaz;

CREATE TABLE operator (                            # -- üzemeltető, szervízes
  ID_OPERATOR int unsigned NOT NULL auto_increment,
  LOGIN       varchar(100) NOT NULL UNIQUE,        # -- bejelentkezési név  + index!
  NEV         varchar(100) NOT NULL,
  EMAIL       varchar(100), 
  RATIFICAT   varchar(100) NOT NULL default LEFT(MD5(RAND()), 32),  # -- ha üres, akkor oksi     
  PASSWORD    varchar(100) NOT NULL default '',    # -- mdX hash-el kódolva
  BEOSZTAS    varchar(100) NOT NULL default '',    # -- orvos, ápoló, adminisztrátor, stb
  PECSET      varchar(100) NOT NULL default '',    # -- orvos pecsét száma
  ADMIN       ENUM('Y','N') NULL DEFAULT 'N',      # -- Tud operátort szerkeszteni
  ADMIN_A     ENUM('Y','N') NULL DEFAULT 'N',      # -- SZ6 projekt A
  ADMIN_B     ENUM('Y','N') NULL DEFAULT 'N',      # -- SZ6 projekt B
  DATUMIDO    timestamp NOT NULL default CURRENT_TIMESTAMP on update CURRENT_TIMESTAMP,
  PRIMARY KEY (ID_OPERATOR)
) ENGINE=InnoDB;

CREATE TABLE config (                               # -- beállítások
  ID_CONFIG  int unsigned NOT NULL auto_increment,
  FIELD  varchar(100) NOT NULL default '',          # -- mezőnév
  VALUE  varchar(100) NOT NULL default '',          # -- érték
  DESCRIPTOR text,                                  # -- hosszú szöveg (pl pdf doksi tartalma...)
  DATUMIDO  timestamp NOT NULL default CURRENT_TIMESTAMP on update CURRENT_TIMESTAMP,
  PRIMARY KEY  (ID_CONFIG) 
) ENGINE=InnoDB;

CREATE TABLE naplo (
  ID_NAPLO int unsigned auto_increment,
  USER varchar(100)    ,
  COMMENT varchar(100) ,   # -- pl. melyik projektből jött ...
  URL varchar(100)     ,
  SQLX VARCHAR(1024)   ,
  DATUMIDO timestamp default CURRENT_TIMESTAMP on update CURRENT_TIMESTAMP,
  PRIMARY KEY (ID_NAPLO),
  INDEX DATUMIDO (DATUMIDO),
  INDEX USER (USER),
  INDEX COMMENT (COMMENT)
) ENGINE=InnoDB ;

CREATE TABLE betegsegek(                                # -- pub. gyógytörzsből feltöltve
  ID_BETEGSEG int unsigned not null auto_increment,
  NEV varchar(255) not null,
  BNO varchar(255) not null,
  PRIMARY key (ID_BETEGSEG),    
  index (NEV), 
  index (BNO) 
) ENGINE=InnoDB ;

CREATE TABLE gyogyszerek(                               # -- pub. gyógytörzsből feltöltve
  ID_GYOGYSZER int unsigned not null auto_increment,
  NEV       varchar(255) not null UNIQUE,
  OEP_DAT   varchar(100) NOT NULL default '',
  HATOANYAG varchar(255) NOT NULL default '',
  MENNYISEG int unsigned not null default 0,
  MEEGYSEG  varchar(255),
  PRIMARY key (ID_GYOGYSZER),
  index (HATOANYAG)   
) ENGINE=InnoDB ;

CREATE TABLE paciensek (
  ID_PACIENS  int unsigned not null AUTO_INCREMENT,
  NEV         varchar(100) not null,
  SZUL_NEV    varchar(100),
  TAJ         varchar(50)  not null UNIQUE,
  ANYJANEVE   varchar(100),
  SZULHELY    varchar(100)  ,
  SZULDATUM   date  not null,
  STATUS      ENUM('várakozó','előgondozott','ellátott','távozott') NULL DEFAULT 'várakozó',      # -- Tud operátort szerkeszteni
  SURGOS_VARAKOZO ENUM('Y','N') NULL DEFAULT 'N',   
  VARAKOZO_DATUM  date,                          # -- várakozói status kezdete
  ELOGOND_DATUM   date,                          # -- előgondozás kezdete
  ELLATOTT_DATUM   date,                         # -- PACIENS start
  TAVOZOTT_DATUM  date,                          # -- PACIENS stop
  IRSZAM      varchar(10),
  TELEPULES   varchar(100),
  UTCAHAZSZ   varchar(100),
  IDEIGLCIM   varchar(100),                      # -- egybe minden (irsz, telep, utca házszám)
  TELEFON     varchar(100),                     
  EMAIL       varchar(100),     
  NYUGDIJ     int unsigned not null default 0,   # -- ellátott nyugdíja  (ft / hó)                  
  LEIRAS      text  comment 'Megjegyzés', 
  DATUMIDO    timestamp NOT NULL default CURRENT_TIMESTAMP on update CURRENT_TIMESTAMP,
  primary key(ID_PACIENS) ,
  INDEX  (NEV) )
ENGINE=InnoDB ; 

CREATE TABLE ellatas (                                           # -- lásd: gondozohaz.xls 
  ID_ELLATAS integer unsigned NOT NULL auto_increment,
  ID_PACIENS integer unsigned NOT NULL               ,   
  EV integer unsigned NOT NULL default YEAR(NOW())   ,           # -- akt. év
  HO integer unsigned NOT NULL default MONTH(NOW())  ,           # -- akt. hó
  NAPOK char(31) NOT NULL default REPEAT("0",31),                # -- 0:hiányzik, 1:jelen, 2:kórház
  NAPIDIJ int unsigned not null default 0,                       # -- nyugdij *60% * 12 / 365 
  FIZETENDO integer unsigned NOT NULL default 0  ,               # -- akt. hó ellátásért tartozik
  FIZETETT  integer NOT NULL default 0  ,                        # -- akt. hó - lehet negatív is (mérleg)
  PRIMARY KEY (ID_ELLATAS), 
  UNIQUE KEY  (ID_PACIENS, EV, HO),                          
  KEY         (ID_PACIENS),
  index       (EV,HO),
  CONSTRAINT xd_m FOREIGN KEY (ID_PACIENS) REFERENCES paciensek (ID_PACIENS) on delete cascade
) ENGINE=innoDB;

CREATE TABLE rokonok (                                    # -- hozzátartozó, kapcsolattartó
  ID_ROKON    int unsigned not null AUTO_INCREMENT,
  NEV         varchar(100) not null,      
  LOGIN       varchar(100) NOT NULL UNIQUE,      # -- email címböl gen.
  PASSWORD    varchar(100) NOT NULL default '',  # -- mdX hash-el kódolv           
  EMAIL       varchar(100),     
  RATIFICAT   varchar(100) NOT NULL default LEFT(MD5(RAND()), 32),  # -- ha üres, akkor oksi 
  CIM         varchar(100),                      # -- egybe minden (irsz, telep, utca házszám)
  TELEFON     varchar(100),                     
  LEIRAS      text  comment 'Megjegyzés', 
  DATUMIDO    timestamp NOT NULL default CURRENT_TIMESTAMP on update CURRENT_TIMESTAMP,
  primary key(ID_ROKON )  ,
  INDEX  (NEV) )
ENGINE=InnoDB ; 

CREATE TABLE paciensek_rokonok (                      # -- N:M reláció
  ID_PR      integer unsigned NOT NULL auto_increment,
  ID_PACIENS integer unsigned NOT NULL               ,   
  ID_ROKON   integer unsigned NOT NULL               ,
  PRIMARY KEY (ID_PR), 
  UNIQUE KEY  pruni (ID_ROKON,ID_PACIENS),                          
  KEY  (ID_PACIENS),
  KEY  (ID_ROKON),
  CONSTRAINT pr_p FOREIGN KEY (ID_PACIENS) REFERENCES paciensek (ID_PACIENS) on delete cascade, 
  CONSTRAINT pr_r FOREIGN KEY (ID_ROKON) REFERENCES   rokonok (ID_ROKON) 
) ENGINE=innoDB;

CREATE TABLE paciensek_gyogyszerek (                      # -- N:M reláció
  ID_PGY       integer unsigned NOT NULL auto_increment,
  ID_PACIENS   integer unsigned NOT NULL               ,   
  ID_GYOGYSZER integer unsigned NOT NULL               ,
  ID_OPERATOR  integer unsigned NOT NULL               ,  # -- felíró orvos
  ADAGOLAS     varchar(100),                     
  LEIRAS       text  comment 'Megjegyzés, recept', 
  DATUMIDO     timestamp NOT NULL default CURRENT_TIMESTAMP on update CURRENT_TIMESTAMP,
  PRIMARY KEY (ID_PGY), 
  UNIQUE KEY  (ID_PGY,ID_PACIENS),                          
  KEY  (ID_PACIENS),
  KEY  (ID_GYOGYSZER),
  KEY  (ID_OPERATOR),
  CONSTRAINT pgy_p  FOREIGN KEY (ID_PACIENS)   REFERENCES paciensek   (ID_PACIENS) on delete cascade, 
  CONSTRAINT pgy_gy FOREIGN KEY (ID_GYOGYSZER) REFERENCES gyogyszerek (ID_GYOGYSZER), 
  CONSTRAINT pgy_o  FOREIGN KEY (ID_OPERATOR)  REFERENCES operator    (ID_OPERATOR) 
) ENGINE=innoDB;

CREATE TABLE paciensek_betegsegek (                      # -- N:M reláció
  ID_PB       integer unsigned NOT NULL auto_increment,
  ID_PACIENS  integer unsigned NOT NULL               ,   
  ID_BETEGSEG integer unsigned NOT NULL               ,
  ID_OPERATOR integer unsigned NOT NULL               ,  # --  orvos                   
  LEIRAS      text  comment 'betegség leírása', 
  DATUMIDO    timestamp NOT NULL default CURRENT_TIMESTAMP on update CURRENT_TIMESTAMP,
  PRIMARY KEY (ID_PB), 
  UNIQUE KEY  (ID_PB,ID_PACIENS),                          
  KEY  (ID_PACIENS),
  KEY  (ID_BETEGSEG),
  KEY  (ID_OPERATOR),
  CONSTRAINT pb_p FOREIGN KEY (ID_PACIENS)  REFERENCES paciensek  (ID_PACIENS) on delete cascade, 
  CONSTRAINT pb_b FOREIGN KEY (ID_BETEGSEG) REFERENCES betegsegek (ID_BETEGSEG), 
  CONSTRAINT pb_o FOREIGN KEY (ID_OPERATOR) REFERENCES operator   (ID_OPERATOR) 
) ENGINE=innoDB;

CREATE TABLE paciensek_korlapok(
  ID_KORLAP   int unsigned not null auto_increment,
  ID_PACIENS  int unsigned not null,
  ID_OPERATOR int unsigned not null,
  LEIRAS      text not null comment 'kezelések leírása, lázlap stb.',
  DATUMIDO    timestamp not null default current_timestamp on update current_timestamp,
  primary key (ID_KORLAP),
  key   (ID_PACIENS ),
  key   (ID_OPERATOR),
  CONSTRAINT korlap_p FOREIGN key (ID_PACIENS)  REFERENCES paciensek (ID_PACIENS) on delete cascade,
  CONSTRAINT korlap_o FOREIGN key (ID_OPERATOR) REFERENCES operator  (ID_OPERATOR))
ENGINE=InnoDB  ;


